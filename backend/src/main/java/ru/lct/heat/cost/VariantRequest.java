package ru.lct.heat.cost;

import java.util.List;

public class VariantRequest {
    public List<Long> targetOrdinals;
    /** 1..3; если не задано, могут быть предприняты все три автоматических профиля. */
    public Integer maxVariants;
    /** Если true, результат, в котором ОКС остаётся неподключённым только из-за незавершённого поиска, отклоняется
     *  (422 SEARCH_INCOMPLETE) вместо возврата с пометкой. По умолчанию false: такой результат возвращается с пометкой,
     *  если полностью доказанного варианта не существует. */
    public Boolean strictCompleteness;
    /** Если true, каждая НОВАЯ камера результата дополнительно несёт короткий `label` и `note` с объяснением, зачем она нужна
     *  (дополнительные свойства, не часть контрактного вывода; результат по умолчанию не меняется). */
    public Boolean explain;
    /** "2D" (по умолчанию) или "DEPTH": необязательный режим с учётом глубины технического приложения (раздел 5). Это отдельный
     *  режим со своими вариантами и своим ранжированием; маршруты могут быть построены заново и не обязаны совпадать с 2D. */
    public String mode;
    public boolean depth(){return mode!=null&&(mode.equalsIgnoreCase("DEPTH")||mode.equalsIgnoreCase("3D"));}
}
